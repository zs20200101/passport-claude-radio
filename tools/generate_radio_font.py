"""Reproduce the dashboard fonts from the licensed, hash-checked variable source.

Requires fonttools==4.60.1 and Node/npm. The static Bold instance is temporary;
only the generated LVGL assets are retained.
"""
import hashlib
from pathlib import Path
import shutil
import subprocess
import tempfile

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/fonts/NotoSansSC-VF.ttf"
EXPECTED = "a3041811a78c361b1de50f953c805e0244951c21c5bd412f7232ef0d899af0da"
BODY_RANGE = "0x20-0x7e,0xb0,0xb7,0x3000-0x303f,0x4e00-0x9fff,0xff01-0xff60"
TITLE_SYMBOLS = "中国之声怀旧音乐清晨两广羊城交通第一财经联网收音机北京上海广州深圳长沙杭州成都"
HINT_SYMBOLS = "上下换台切确定播放长按设置进入单击调音量双"
DASHBOARD_SYMBOLS = "".join(sorted({c for path in [* (ROOT / "main").glob("*.cc"),
    ROOT / "tools/claude_lan_bridge/bridge.py", ROOT / "tools/claude_lan_bridge/companion.py"]
    for c in path.read_text(encoding="utf-8") if "\u4e00" <= c <= "\u9fff"}))


def main():
    if hashlib.sha256(SOURCE.read_bytes()).hexdigest() != EXPECTED:
        raise SystemExit("Unexpected source font SHA256")
    npx = shutil.which("npx.cmd") or shutil.which("npx") or "npx"
    with tempfile.TemporaryDirectory(prefix="passport-bold-") as directory:
        instance = Path(directory) / "NotoSansSC-Bold.ttf"
        with TTFont(SOURCE, recalcTimestamp=False) as variable:
            bold = instantiateVariableFont(variable, {"wght": 700}, inplace=False)
            bold.save(instance)
        fonts = [
            ("radio_font", "assets/fonts/passport_font_16.c", 16, 2, BODY_RANGE, ""),
            ("radio_font_dashboard", "assets/fonts/passport_font_dashboard.c", 16, 4, "0x20-0x7e,0xb0,0xb7,0xff1a,0xff0c", DASHBOARD_SYMBOLS),
            ("radio_font_title", "main/radio_font_title.c", 20, 4, "0x20-0x7e", TITLE_SYMBOLS),
            ("radio_font_small", "assets/fonts/passport_font_14.c", 14, 4, "0x20-0x7e", HINT_SYMBOLS),
            ("radio_font_clock", "assets/fonts/passport_font_40.c", 40, 4, "0x2d,0x30-0x3a", ""),
        ]
        for name, output, size, bpp, ranges, symbols in fonts:
            command = [npx, "--yes", "--package=lv_font_conv@1.5.3", "lv_font_conv",
                       "--font", str(instance), "--range", ranges, "--size", str(size),
                       "--bpp", str(bpp), "--no-compress", "--no-kerning", "--format", "lvgl",
                       "--lv-include", "lvgl.h", "--lv-font-name", name, "-o", output]
            if symbols:
                command += ["--symbols", symbols]
            subprocess.run(command, cwd=ROOT, check=True)
            target = ROOT / output
            text = target.read_text(encoding="utf-8").replace(str(instance), "NotoSansSC-Bold.ttf")
            target.write_text("/* Noto Sans SC Bold: wght=700; generated by tools/generate_radio_font.py. */\n" + text,
                              encoding="utf-8", newline="\n")
            print("Generated", output, flush=True)


if __name__ == "__main__":
    main()
